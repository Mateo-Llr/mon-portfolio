function selectProject(index, openSheet = true) {
  const project = projects[index];
  if (!project) return;

  if (insertedCassetteIndex !== null && insertedCassetteIndex !== index) {
    roomScene.setCassetteInserted?.(insertedCassetteIndex, false);
  }

  roomScene.setCassetteInserted?.(index, true);
  roomScene.updateScreen?.(project, false);
  insertedCassetteIndex = index;

  if (openSheet) openProjectSheet(index);
}

function openProjectSheet(index) {
  const project = projects[index];
  if (!project) return;

  const screenTheme = project.screenTheme || {};
  const sheetTheme = {
    "--sheet-background": screenTheme.background || "#182c2d",
    "--sheet-grid": screenTheme.grid || "rgba(101, 198, 194, .055)",
    "--sheet-accent": screenTheme.accent || "#65c6c2",
    "--sheet-highlight": screenTheme.primary || "#c3eee0",
    "--sheet-ink": screenTheme.body || "#e7dfcc",
    "--sheet-muted": screenTheme.sectionBody || "#b9b9a7",
    "--sheet-title-glow": screenTheme.titleGlow || "rgba(101, 198, 194, .14)"
  };
  Object.entries(sheetTheme).forEach(([property, value]) => {
    projectSheet.style.setProperty(property, value);
  });
  sheetKicker.textContent = project.date || `ARCHIVE / 0${index + 1}`;
  sheetIndex.textContent = `PROJECT 0${index + 1}`;
  sheetTitle.innerHTML = project.gameTitleTexture
    ? `<img class="sheet-game-title-image" src="${project.gameTitleImage}" alt="${project.title.replace(/<br>/g, " ")}">`
    : project.title;
  sheetMeta.innerHTML = project.meta;
  sheetProjectMeta.innerHTML = project.projectMeta || "";
  sheetLead.textContent = project.lead;
  sheetContent.innerHTML = project.content;
  const gallery = sheetContent.querySelector(".sheet-gallery");
  if (gallery && project.galleryImages) {
    gallery.classList.remove("sheet-gallery-empty");
    gallery.replaceChildren(...project.galleryImages.map(({ src, alt }) => {
      const image = document.createElement("img");
      image.src = src;
      image.alt = alt;
      return image;
    }));
  }
  projectSheet.classList.add("is-visible");
  projectSheet.setAttribute("aria-hidden", "false");
  document.body.classList.add("is-sheet-open");
}

function closeProjectSheet() {
  projectSheet.classList.remove("is-visible");
  projectSheet.setAttribute("aria-hidden", "true");
  document.body.classList.remove("is-sheet-open");
}

function openTrophyPanel(id) {
  const trophy = trophies[id];
  if (!trophy || !trophyPanel) return;
  trophyPanelReturnFocus = document.activeElement instanceof HTMLElement ? document.activeElement : null;
  trophyPanelTitle.innerHTML = trophy.title;
  if (trophyPanelType) trophyPanelType.innerHTML = trophy.meta;
  trophyPanelDescription.textContent = trophy.description;
  trophyPanel.inert = false;
  trophyPanel.classList.add("is-visible");
  trophyPanel.setAttribute("aria-hidden", "false");
  trophyPanelClose?.focus();
}

function closeTrophyPanel() {
  if (!trophyPanel) return;
  const returnFocus = trophyPanelReturnFocus && !trophyPanel.contains(trophyPanelReturnFocus)
    ? trophyPanelReturnFocus
    : document.body;
  if (typeof returnFocus.focus === "function") {
    if (returnFocus === document.body) document.body.setAttribute("tabindex", "-1");
    returnFocus.focus({ preventScroll: true });
    if (returnFocus === document.body) document.body.removeAttribute("tabindex");
  }
  trophyPanel.inert = true;
  trophyPanel.classList.remove("is-visible");
  trophyPanel.setAttribute("aria-hidden", "true");
  trophyPanelReturnFocus = null;
  roomScene.closeTrophyShowcase();
}

